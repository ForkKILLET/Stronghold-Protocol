#!/usr/bin/env node
// Presentation-only, fixed Unicode readings; no changes to gameplay tables or version identities.
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ZipReader, Uint8ArrayReader, TextWriter } from '@zip.js/zip.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');

export function plainReading(text) {
  return text.toLowerCase().normalize('NFD').replace(/u\u0308/g, 'v').replace(/[\u0300\u0301\u0304\u030c]/g, '').normalize('NFC');
}

/** The four documented Mandarin fields use either readings, or dictionary-position:reading,reading groups. */
export function parseReadings(text, wanted, fields) {
  const values = new Map();
  for (const line of text.split('\n')) {
    const [code, field, value] = line.split('\t');
    if (!/^U\+[0-9A-F]+$/.test(code) || !fields.includes(field)) continue;
    const char = String.fromCodePoint(parseInt(code.slice(2), 16));
    if (!wanted.has(char)) continue;
    const set = values.get(char) || new Set();
    for (const group of value.trim().split(/\s+/)) {
      for (const reading of group.slice(group.indexOf(':') + 1).split(',')) {
        const syllable = plainReading(reading);
        if (!/^[a-zv]+$/.test(syllable)) throw Error(`Invalid reading ${char}: ${reading}`);
        set.add(syllable);
      }
    }
    values.set(char, set);
  }
  return Object.fromEntries([...values].sort(([a], [b]) => a < b ? -1 : 1).map(([char, values]) => [char, [...values].sort()]));
}

/** All shipped seasons and localisations, including DIY backups and fixed profile avatar names. */
export async function searchVocabulary(root = ROOT) {
  const texts = new Set(['先锋', '近卫', '重装', '狙击', '术师', '医疗', '辅助', '特种']);
  const operators = new Map();
  async function walk(dir) {
    for (const item of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name < b.name ? -1 : 1)) {
      const file = join(dir, item.name);
      if (item.isDirectory()) { await walk(file); continue; }
      if (!['chess.json', 'backups.json', 'bonds.json', 'profile-avatars.json'].includes(item.name)) continue;
      const data = JSON.parse(await readFile(file, 'utf8'));
      const records = item.name === 'backups.json' ? [...Object.values(data.units || {}), ...Object.values(data.diy?.operators || {})]
        : Object.values(item.name === 'profile-avatars.json' ? data.avatars || {} : data);
      for (const record of records) {
        for (const key of ['name', 'appellation', 'subProfessionName']) if (typeof record[key] === 'string') texts.add(record[key]);
        if (!file.replaceAll('\\', '/').includes('/i18n/') && record.charId && record.name) {
          const names = operators.get(record.charId) || new Set();
          names.add(record.name); operators.set(record.charId, names);
        }
      }
    }
  }
  await walk(join(root, 'data'));
  const chars = new Set([...texts].flatMap(text => [...text].filter(char => /\p{Script=Han}/u.test(char))));
  const names = Object.fromEntries([...operators].sort(([a], [b]) => a < b ? -1 : 1).map(([id, names]) => [id, [...names].sort()]));
  return { chars, names };
}

export async function buildSearchPinyin({ root = ROOT, offline = false, check = false } = {}) {
  const source = JSON.parse(await readFile(join(ROOT, 'tools/search-pinyin-sources.json'), 'utf8'));
  const cache = join(root, '.cache/search-pinyin');
  const cached = join(cache, 'Unihan-17.0.0.zip');
  let bytes;
  try { bytes = await readFile(cached); } catch (error) {
    if (error.code !== 'ENOENT' || offline) throw error;
  }
  if (!bytes) {
    const response = await fetch(source.url, { signal: AbortSignal.timeout(60000) });
    if (!response.ok) throw Error('Unihan HTTP ' + response.status);
    bytes = Buffer.from(await response.arrayBuffer());
  }
  if (sha(bytes) !== source.sha256) throw Error('Unihan archive checksum mismatch');
  const reader = new ZipReader(new Uint8ArrayReader(bytes), { useWebWorkers: false });
  let readings;
  try {
    const entry = (await reader.getEntries()).find(entry => entry.filename === source.entry);
    if (!entry || entry.directory) throw Error('Missing Unihan readings');
    readings = await entry.getData(new TextWriter());
  } finally { await reader.close(); }
  if (sha(readings) !== source.entrySha256) throw Error('Unihan readings checksum mismatch');
  const { chars, names } = await searchVocabulary(root);
  const map = parseReadings(readings, chars, source.fields);
  const missing = [...chars].filter(char => !map[char]);
  if (missing.length) throw Error('Missing Mandarin search readings: ' + missing.join(''));
  const generated = '// Generated by tools/build-search-pinyin.mjs; do not edit.\n'
    + '// i18n-ignore-file: Chinese names and readings are search data, not interface text.\n'
    + '// Unicode 17.0.0 / Unicode-3.0; see THIRD-PARTY-NOTICES.md and docs/OPERATOR_SEARCH.md.\n'
    + '// Readings are search alternatives, not claims about official operator pronunciation.\n'
    + `export const SEARCH_READINGS = ${JSON.stringify(map)};\n`
    + `export const OPERATOR_SEARCH_NAMES = ${JSON.stringify(names)};\n`;
  const output = join(root, 'public/js/ui/searchReadings.js');
  if (check) {
    if (await readFile(output, 'utf8') !== generated) throw Error('Stale searchReadings.js; regenerate after updating the vocabulary');
  } else {
    await mkdir(cache, { recursive: true });
    await writeFile(cached, bytes);
    await writeFile(output, generated);
  }
  return { characters: chars.size, operators: Object.keys(names).length, bytes: Buffer.byteLength(generated) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some(arg => !['--offline', '--check'].includes(arg))) throw Error('Usage: node tools/build-search-pinyin.mjs [--offline] [--check]');
  console.log(await buildSearchPinyin({ offline: args.includes('--offline'), check: args.includes('--check') }));
}
